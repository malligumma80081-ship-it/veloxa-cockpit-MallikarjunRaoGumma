"""Generates the populated Evidence_Index.xlsx workbook."""
from pathlib import Path
from typing import Optional
import openpyxl
from app.config import EXPORTS_DIR
from app.evidence.repository import EvidenceRepository


class EvidenceIndexer:
    def __init__(self, repo: Optional[EvidenceRepository] = None):
        self.repo = repo or EvidenceRepository()

    def export_index(self, target_path: Optional[Path] = None, as_of_date: str = "2026-11-16") -> Path:
        target_path = target_path or (EXPORTS_DIR / "Evidence_Index.xlsx")
        target_path.parent.mkdir(parents=True, exist_ok=True)

        wb = openpyxl.Workbook()
        ws = wb.active
        ws.title = "Evidence index"

        ws.append(["One fact per row. Generated by Veloxa CXO Cockpit Evidence Indexer."])
        ws.append([])
        ws.append([
            "Ref",
            "File",
            "Sheet / page / row",
            "Fact (your words)",
            "Entities named",
            "Date (as written)",
            "Date (normalised, IST)",
            "Confidence (H/M/L)",
        ])

        # Get evidence as of date (excluding restricted individual salaries)
        evidence_list = self.repo.get_evidence_point_in_time(as_of_date=as_of_date, exclude_restricted=True)

        for ev in evidence_list:
            conf_char = "H" if ev.confidence == "high" else ("M" if ev.confidence == "medium" else "L")
            entities_str = ", ".join(ev.entity_ids)
            ws.append([
                ev.evidence_id,
                ev.source_file,
                ev.locator,
                ev.claim,
                entities_str,
                ev.event_date or "N/A",
                ev.event_date or "N/A",
                conf_char,
            ])

        wb.save(target_path)
        return target_path
